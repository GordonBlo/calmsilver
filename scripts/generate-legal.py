"""Generate policy pages and modal content from the same reviewed translations."""
from pathlib import Path
from html import escape
import json
import re

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / 'dist'
DATA = json.loads((ROOT / 'legal/policies.json').read_text())
LANGUAGES = {'ro': 'Română', 'en': 'English', 'hu': 'Magyar'}


def filename(policy, lang):
    return policy + ('' if lang == 'ro' else '-' + lang) + '.html'


def render(policy, lang):
    t = DATA[lang]
    p = t[policy]
    out = [f'<p class="legal-updated"><time datetime="{DATA["date"]}">{escape(t["updated"])}</time></p>']
    if DATA['status'] != 'approved':
        out.append(f'<p class="legal-review-note">{escape(t["review"])}</p>')
    for index, section in enumerate(p['sections']):
        out.append('<section class="legal-section"><h3>' + escape(section['title']) + '</h3>')
        for paragraph in section['paragraphs']:
            # Only known contact literals become links; all supplied text is escaped.
            text = escape(paragraph)
            text = text.replace('hello@calmsilver.com', '<a href="mailto:hello@calmsilver.com">hello@calmsilver.com</a>')
            text = text.replace('https://calmsilver.com', '<a href="https://calmsilver.com">https://calmsilver.com</a>')
            out.append('<p>' + text + '</p>')
        if policy == 'cookies' and index == 1:
            out.append(f'<p class="legal-table-hint">{escape(p["tableHint"])}</p>')
            out.append(f'<div class="legal-table-wrap" tabindex="0" role="region" aria-label="{escape(p["inventoryTitle"], quote=True)}">')
            out.append('<table><caption>' + escape(p['inventoryTitle']) + '</caption><thead><tr>')
            out += ['<th scope="col">' + escape(v) + '</th>' for v in p['columns']]
            out.append('</tr></thead><tbody>')
            for row in p['rows']:
                assert len(row) == len(p['columns'])
                out.append('<tr><th scope="row">' + escape(row[0]) + '</th>')
                out += ['<td>' + escape(v) + '</td>' for v in row[1:]]
                out.append('</tr>')
            out.append('</tbody></table></div>')
        out.append('</section>')
    out.append('<ul class="legal-sources">')
    for link in p['links']:
        href = filename(link['policy'], lang) if 'policy' in link else link['href']
        assert not re.match(r'[a-z]+:', href) or href.startswith('https://')
        out.append(f'<li><a href="{escape(href, quote=True)}">{escape(link["label"])}</a></li>')
    out.append('</ul>')
    return '\n'.join(out)


contents = {lang: {policy: render(policy, lang) for policy in ('privacy', 'cookies')} for lang in LANGUAGES}
index = (DIST / 'index.html').read_text()
for policy in ('privacy', 'cookies'):
    pattern = rf'(<div data-legal-policy="{policy}">).*?(</div><!-- legal:{policy} -->)'
    index, count = re.subn(pattern, lambda m: m[1] + contents['ro'][policy] + m[2], index, flags=re.S)
    assert count == 1, policy
(DIST / 'index.html').write_text(index)

runtime = """'use strict';
// Generated by scripts/generate-legal.py; edit legal/policies.json instead.
(() => {
  const contents = __CONTENTS__;
  function render() {
    const lang = Object.hasOwn(contents, document.documentElement.lang) ? document.documentElement.lang : 'ro';
    for (const node of document.querySelectorAll('[data-legal-policy]')) node.innerHTML = contents[lang][node.dataset.legalPolicy];
    for (const link of document.querySelectorAll('[data-policy-link]')) link.setAttribute('href', link.dataset.policyLink + (lang === 'ro' ? '' : '-' + lang) + '.html');
  }
  window.addEventListener('calmsilver:language', render);
  render();
})();
"""
(DIST / 'legal.js').write_text(runtime.replace('__CONTENTS__', json.dumps(contents, ensure_ascii=False)))

for lang in LANGUAGES:
    for policy in ('privacy', 'cookies'):
        t, p = DATA[lang], DATA[lang][policy]
        home = 'index.html' + ('' if lang == 'ro' else '?lang=' + lang)
        nav = ' / '.join(f'<a lang="{code}" href="{filename(policy, code)}"' + (' aria-current="page"' if code == lang else '') + f'>{escape(label)}</a>' for code, label in LANGUAGES.items())
        settings = ''
        if policy == 'cookies':
            settings = f'<p class="legal-settings-link"><a class="text-link" href="{home}#cookie-settings">{escape(t["settings"])}</a></p>'
        page = f'''<!doctype html>
<html lang="{lang}">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="referrer" content="strict-origin-when-cross-origin">
  <meta name="robots" content="noindex">
  <title>{escape(p['title'])} | CalmSilver</title>
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="styles.css"><link rel="stylesheet" href="legal.css">
</head>
<body class="legal-page">
  <header class="legal-page-header page-width"><a class="wordmark" href="{home}">CalmSilver<span class="wordmark-dot">.</span></a><a href="{home}">{escape(t['back'])}</a></header>
  <main class="page-width legal-document" id="main">
    <nav class="legal-language-nav" aria-label="Language / Limbă / Nyelv">{nav}</nav>
    <h1>{escape(p['title'])}</h1>
    {contents[lang][policy]}
    {settings}
  </main>
  <footer class="page-width legal-page-footer"><a href="{home}">{escape(t['back'])}</a> · <a href="mailto:hello@calmsilver.com">hello@calmsilver.com</a></footer>
</body>
</html>
'''
        (DIST / filename(policy, lang)).write_text('\n'.join(line.rstrip() for line in page.splitlines()) + '\n')
print('Generated six static policy pages and matching RO/EN/HU dialog content.')
